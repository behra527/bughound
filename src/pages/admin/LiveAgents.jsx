import { useEffect, useState } from 'react'
import { Check, Code2, Download, Shield } from 'lucide-react'
import Shell from '../../components/Shell'
import { AgentCards, StatusBadge, TicketBanner } from '../../components/ui'
import { liveLogs } from '../../data'
import { useApp } from '../../context'

export default function LiveAgents() {
  const { tickets, notify } = useApp()
  const ticket = tickets[0]
  const [tab, setTab] = useState('Live Logs')
  const [auto, setAuto] = useState(true)
  const [lines, setLines] = useState(liveLogs.slice(0, 4))

  useEffect(() => {
    if (!auto || lines.length >= liveLogs.length) return undefined
    const id = setTimeout(() => setLines(liveLogs.slice(0, lines.length + 1)), 900)
    return () => clearTimeout(id)
  }, [auto, lines])

  return (
    <Shell title="Live AI Agents Workflow" subtitle="Real-time execution, logs, and results of all AI agents for ticket resolution.">
      <TicketBanner ticket={ticket} />
      <div className="split">
        <div className="card">
          <div className="card-head"><h3>AI Agents Workflow (Live Execution)</h3><span className="badge b-live">Live Execution</span></div>
          <AgentCards active={2} />
        </div>
        <div className="card">
          <h3>Execution Summary</h3>
          <div className="kv">
            <span>Current Agent</span><b>Agent 3 – Patch Generator</b>
            <span>Status</span><StatusBadge status="Running" />
            <span>Started At</span><b>Nov 10, 2026, 02:14:30 PM</b>
            <span>Elapsed Time</span><b>00:00:45</b>
            <span>LLM (OpenRouter)</span><b>gpt-4o</b>
            <span>Retries</span><b>0 / 3</b>
          </div>
        </div>
      </div>
      <div className="split" style={{ marginTop: 14 }}>
        <div className="card">
          <div className="tabs">
            {['Live Logs', 'Agent Results', 'Artifacts', 'Execution History'].map((name) => (
              <button key={name} className={tab === name ? 'on' : ''} onClick={() => setTab(name)}>{name}</button>
            ))}
          </div>
          {tab === 'Live Logs' && (
            <>
              <div className="card-head">
                <h3>Execution Logs – Agent 3 (Patch Generator)</h3>
                <div style={{ display: 'flex', gap: 8, alignItems: 'center' }}>
                  <span className="badge b-live">Running</span>
                  Auto Scroll
                  <button className={`toggle ${auto ? 'on' : ''}`} onClick={() => setAuto((v) => !v)}><i /></button>
                  <button className="btn btn-ghost" onClick={() => setLines([])}>Clear</button>
                </div>
              </div>
              <div className="code">
                {lines.map(([time, text]) => <div key={time}>[{time}] <span className="c">INFO</span> {text}</div>)}
                {!lines.length && <div>Logs cleared. Turn auto scroll back on to stream again.</div>}
              </div>
            </>
          )}
          {tab === 'Agent Results' && <p>Investigator and Validator completed. Patch Generator is writing app/auth/service.py.</p>}
          {tab === 'Artifacts' && <Artifacts notify={notify} />}
          {tab === 'Execution History' && <p className="hint">Run #18 · Agent 3 · started 02:14:30 PM · still running.</p>}
          {tab === 'Live Logs' && <Artifacts notify={notify} />}
        </div>
        <div className="side-stack">
          <div className="card">
            <h3>Agent Progress</h3>
            {[['Agent 1 – Investigator', 'Completed · 1m 24s', 'done'], ['Agent 2 – Validator', 'Completed · 1m 10s', 'done'], ['Agent 3 – Patch Generator', 'Running · 45s', 'run'], ['Agent 4 – Testing', 'Pending', '']].map(([name, state]) => (
              <div key={name} className="checkline" style={{ color: '#3f3958' }}><Check size={14} color="#16a34a" /> <div><b>{name}</b><div className="hint">{state}</div></div></div>
            ))}
          </div>
          <div className="card">
            <h3>Next Steps</h3>
            {['Generate patch and create diff (Agent 3)', 'Run automated tests (Agent 4)', 'Review patch and approve (Admin)', 'Create GitHub pull request', 'Update ticket resolution status'].map((text, i) => (
              <div className="checkline" key={text} style={{ color: '#3f3958' }}>{i === 0 ? '●' : '○'} {text}</div>
            ))}
          </div>
        </div>
      </div>
    </Shell>
  )
}

