import { useState } from 'react'
import { useNavigate } from 'react-router-dom'
import { Download, Play } from 'lucide-react'
import Shell from '../../components/Shell'
import { AgentCards, TicketBanner } from '../../components/ui'
import { useApp } from '../../context'

const original = [
  [40, 'def authenticate_user(email: str, password: str):'],
  [41, '    user = db.query(User).filter('],
  [42, '        User.email == email).first()'],
  [43, ''],
  [44, '    if not user:'],
  [45, '        return None'],
  [46, '    if user.password == password:', 'bad'],
  [47, '        return user', 'bad'],
  [48, '    return None', 'bad'],
]
const corrected = [
  [40, 'def authenticate_user(email: str, password: str):'],
  [41, '    user = db.query(User).filter('],
  [42, '        User.email == email).first()'],
  [43, ''],
  [44, '    if not user:'],
  [45, '        return None'],
  [46, '    # Verify hashed password using bcrypt', 'good'],
  [47, '    if verify_password(password, user.password_hash):', 'good'],
  [48, '        return user', 'good'],
  [49, '    return None', 'good'],
]

export default function DiffViewer() {
  const { tickets, notify } = useApp()
  const navigate = useNavigate()
  const [tab, setTab] = useState('Diff Viewer')
  const [file, setFile] = useState('app/auth/service.py')
  const ticket = tickets[0]

  const download = () => {
    const text = corrected.map(([, line]) => line).join('\n')
    const blob = new Blob([text], { type: 'text/plain' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = 'patch.diff'
    a.click()
    URL.revokeObjectURL(url)
    notify('Diff downloaded')
  }

  return (
    <Shell title="Original vs Corrected Code (Diff Viewer)" subtitle="Review the patch generated by Agent 3, compare changes, and validate the fix.">
      <TicketBanner ticket={ticket} />
      <div className="card" style={{ marginBottom: 14 }}><AgentCards active={2} complete compact /></div>
      <div className="tabs">
        {['Diff Viewer', 'Patch Files (2)', 'Patch Summary', 'AI Explanation', 'Execution Logs'].map((name) => (
          <button key={name} className={tab === name ? 'on' : ''} onClick={() => setTab(name)}>{name}</button>
        ))}
      </div>
      {tab === 'Diff Viewer' || tab === 'Patch Files (2)' ? (
        <div className="three" style={{ gridTemplateColumns: '240px 1fr 260px' }}>
          <div className="card">
            <h3>Modified Files (2)</h3>
            {['app/auth/service.py', 'app/auth/routes.py'].map((name) => (
              <label key={name} className="check" style={{ margin: '8px 0' }}>
                <input type="checkbox" checked={file === name} onChange={() => setFile(name)} /> {name} <span className="tag m">M</span>
              </label>
            ))}
          </div>
          <div className="card">
            <div className="card-head"><h3>{file} · Modified</h3><span className="hint">−12 +14</span></div>
            <div className="pair">
              <Pane title="Original Code (a1b2c3d)" rows={original} />
              <Pane title="Corrected Code (Patch)" rows={file.endsWith('routes.py') ? [[12, '@router.post("/login")', 'good']] : corrected} />
            </div>
          </div>
          <Side navigate={navigate} notify={notify} download={download} />
        </div>
      ) : (
        <div className="card"><p>{tab}: Agent 3 replaced the plain-text comparison with bcrypt.verify() so valid credentials succeed.</p></div>
      )}
      <div className="two-col" style={{ marginTop: 14 }}>
        <div className="card">
          <h3>Change Details</h3>
          <div className="kv"><span>Change Type</span><b>Security Fix</b><span>Severity</span><b>High</b><span>Affected Module</span><b>Authentication</b><span>Impact</span><b>Fixes login failure for valid users</b></div>
        </div>
        <div className="card">
          <h3>Commit Message (Proposed)</h3>
          <pre className="hint">{`fix(auth): use bcrypt verification for password validation
- Replace plain text password comparison with bcrypt.verify()
- Fixes login failure for valid credentials
- Improves authentication security`}</pre>
        </div>
      </div>
      <div className="actions-bar">
        <button className="btn btn-ghost" onClick={() => navigate('/admin/testing')}><Play size={14} /> Execute Tests</button>
        <button className="btn btn-ghost" onClick={() => notify('Full patch opened')}>View Full Patch</button>
        <button className="btn btn-ghost" onClick={download}><Download size={14} /> Download Diff</button>
        <button className="btn btn-primary" onClick={() => navigate('/admin/github')}>Approve Patch</button>
        <button className="btn btn-danger" onClick={() => notify('Patch rejected')}>Reject Patch</button>
      </div>
    </Shell>
  )
}

function Pane({ title, rows }) {
  return (
    <div className="pane">
      <h4>{title}</h4>
      <div className="light-code">
        {rows.map(([n, text, kind]) => <div className={`ln ${kind || ''}`} key={title + n}><b>{n}</b><span>{text || ' '}</span></div>)}
      </div>
    </div>
  )
}

function Side({ navigate, download }) {
  return (
    <div className="side-stack">
      <div className="card">
        <h3>Patch Summary</h3>
        <div className="kv"><span>Files Modified</span><b>2</b><span>Lines Added</span><b style={{ color: '#16a34a' }}>+14</b><span>Lines Removed</span><b style={{ color: '#dc2626' }}>−12</b><span>Net Changes</span><b>+2</b></div>
      </div>
      <div className="card">
        <h3>AI Explanation (Agent 3)</h3>
        <p className="hint">Replaced plain text password comparison with a secure hash verification using bcrypt.verify(). This fixes the login failure for valid credentials.</p>
      </div>
      <div className="card">
        <h3>Testing Status</h3>
        <div className="checkline"><span style={{ color: '#16a34a' }}>✓</span> Unit Tests 5 / 5 Passed</div>
        <div className="hint">○ Integration Tests Pending</div>
        <div className="hint">○ Regression Tests Pending</div>
        <button className="btn btn-soft btn-block" style={{ marginTop: 8 }} onClick={() => navigate('/admin/testing')}>Run remaining tests</button>
        <button className="btn btn-ghost btn-block" style={{ marginTop: 8 }} onClick={download}>Download Diff</button>
      </div>
    </div>
  )
}
